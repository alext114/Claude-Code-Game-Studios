#!/usr/bin/env python3
"""codex-sync — generate .codex/ and AGENTS.md from .claude/.

.claude/ is the single source of truth, written in Claude Code idiom. This
script emits the Codex equivalents. Generated files are committed; a CI drift
guard (--check) fails if they are stale or hand-edited.

See docs/codex-port-plan.md.

Phase status
    0  scaffolding + shared rewriting        done
    1  AGENTS.md                             done
    2  .codex/hooks.json                     stub
    3  .codex/agents/*.toml                  stub
    4  .codex/skills/*/SKILL.md              stub

Output must be deterministic: --check regenerates and byte-compares, so no
timestamps or unordered iteration anywhere in generated content.
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CLAUDE = REPO / ".claude"
CODEX = REPO / ".codex"
MAPPINGS = Path(__file__).parent / "mappings.toml"

HEADER_MD = "<!-- GENERATED by tools/codex-sync — do not edit. Source: {source} -->"
HEADER_TOML = "# GENERATED by tools/codex-sync — do not edit. Source: {source}"

IMPORT_RE = re.compile(r"^@(\S+)[ \t]*$", re.M)
MAX_IMPORT_DEPTH = 5


# --------------------------------------------------------------------------
# Loading
# --------------------------------------------------------------------------

def load_mappings() -> dict:
    with MAPPINGS.open("rb") as fh:
        return tomllib.load(fh)


def skill_names() -> list[str]:
    """The closed set of skill names. This is what makes /x -> $x safe."""
    return sorted(p.parent.name for p in CLAUDE.glob("skills/*/SKILL.md"))


def agent_names() -> list[str]:
    return sorted(p.stem for p in CLAUDE.glob("agents/*.md"))


def split_frontmatter(text: str) -> tuple[str, str]:
    """Return (frontmatter, body). Frontmatter excludes the --- delimiters."""
    if not text.startswith("---"):
        return "", text
    end = text.find("\n---", 3)
    if end == -1:
        return "", text
    return text[4:end], text[end + 4:].lstrip("\n")


# --------------------------------------------------------------------------
# Body rewriting  (port plan §6.3)
# --------------------------------------------------------------------------

def _skill_ref_pattern(names: list[str]) -> re.Pattern:
    """Match /skill-name only when it is a command reference, not a path.

    Guards against the R5 failure mode: /help must be rewritten, but
    docs/help/x and </div> must not.
    """
    alt = "|".join(re.escape(n) for n in sorted(names, key=len, reverse=True))
    return re.compile(rf"(?<![\w./-])/({alt})(?![\w/-])")


def rewrite_skill_refs(text: str, names: list[str]) -> str:
    return _skill_ref_pattern(names).sub(lambda m: "$" + m.group(1), text)


def rewrite_tool_names(text: str, mappings: dict) -> str:
    """Rewrite Claude tool names to Codex equivalents.

    Safe names are rewritten anywhere. Contextual names are English words and
    are rewritten only inside backticks or in an explicit "X tool" phrasing,
    so "Read the story file" is left alone.
    """
    for claude, codex in mappings["tool_names"].items():
        text = re.sub(rf"\b{re.escape(claude)}\b", codex, text)

    for claude, codex in mappings["tool_names_contextual"].items():
        text = re.sub(rf"`{re.escape(claude)}`", f"`{codex}`", text)
        text = re.sub(rf"\b{re.escape(claude)} tool\b", f"{codex} tool", text)
    return text


def rewrite_body(text: str, names: list[str], mappings: dict) -> str:
    return rewrite_tool_names(rewrite_skill_refs(text, names), mappings)


# --------------------------------------------------------------------------
# Markdown helpers
# --------------------------------------------------------------------------

def demote_headings(text: str, levels: int) -> str:
    """Demote ATX headings by `levels`, skipping fenced code blocks.

    Imported docs open at h1. Inlined under an h2 section they need to nest,
    or the document hierarchy inverts.
    """
    out, in_fence, fence = [], False, ""
    for line in text.split("\n"):
        stripped = line.lstrip()
        if stripped.startswith("```") or stripped.startswith("~~~"):
            marker = stripped[:3]
            if not in_fence:
                in_fence, fence = True, marker
            elif marker == fence:
                in_fence, fence = False, ""
            out.append(line)
            continue
        if not in_fence:
            m = re.match(r"^(#{1,6})(\s)", line)
            if m:
                line = "#" * min(6, len(m.group(1)) + levels) + line[len(m.group(1)):]
        out.append(line)
    return "\n".join(out)


def _norm(title: str) -> str:
    return re.sub(r"[^a-z0-9]", "", title.lower())


def _last_heading(text: str) -> tuple[int, str] | None:
    """The heading immediately above an import point."""
    matches = re.findall(r"^(#{1,6})[ \t]+(.+?)[ \t]*$", text, re.M)
    if not matches:
        return None
    hashes, title = matches[-1]
    return len(hashes), title


def _first_heading(text: str) -> tuple[int, str, str] | None:
    """The imported doc's own title line, if it opens with one."""
    m = re.search(r"^(#{1,6})[ \t]+(.+?)[ \t]*$", text, re.M)
    if not m:
        return None
    return len(m.group(1)), m.group(2), m.group(0)


def _is_redundant(parent: str, child: str) -> bool:
    """True when the imported title restates the section heading above it."""
    a, b = _norm(parent), _norm(child)
    return a in b or b in a


def inline_imports(text: str, seen: frozenset[Path], depth: int,
                   order: list[str]) -> str:
    """Recursively inline Claude Code @path imports.

    Imported docs open at h1. Inlined beneath an h2 section they must nest, so
    headings are demoted to sit one level under the parent. When the imported
    title merely restates the section heading above it ("## Technical
    Preferences" followed by "# Technical Preferences") the duplicate title is
    dropped instead of demoted.
    """
    if depth > MAX_IMPORT_DEPTH:
        raise RuntimeError(f"@import nesting exceeded {MAX_IMPORT_DEPTH} levels")

    def repl(match: re.Match) -> str:
        rel = match.group(1)
        path = (REPO / rel).resolve()
        if path in seen:
            return f"<!-- codex-sync: cyclic import skipped: {rel} -->"
        if not path.is_file():
            raise FileNotFoundError(f"@import target missing: {rel}")
        order.append(rel)
        content = path.read_text(encoding="utf-8").strip("\n")
        content = inline_imports(content, seen | {path}, depth + 1, order)

        parent = _last_heading(match.string[:match.start()])
        parent_level = parent[0] if parent else 1

        first = _first_heading(content)
        if first and parent and first[0] == 1 and _is_redundant(parent[1], first[1]):
            content = content.replace(first[2], "", 1).lstrip("\n")
            content = demote_headings(content, parent_level - 1)
        else:
            content = demote_headings(content, parent_level)

        return f"<!-- inlined from {rel} -->\n\n{content}"

    return IMPORT_RE.sub(repl, text)


# --------------------------------------------------------------------------
# Phase 1 — AGENTS.md
# --------------------------------------------------------------------------

def generate_agents_md(mappings: dict) -> dict[Path, str]:
    source = REPO / "CLAUDE.md"
    text = source.read_text(encoding="utf-8").strip("\n")

    order: list[str] = []
    text = inline_imports(text, frozenset({source.resolve()}), 0, order)
    text = rewrite_body(text, skill_names(), mappings)

    chain = "\n".join(f"<!--   {rel} -->" for rel in order)
    header = "\n".join([
        HEADER_MD.format(source="CLAUDE.md"),
        "<!-- Inlined @imports, in order: -->",
        chain,
        "",
        "",
    ])
    content = header + text + "\n"

    limit = mappings["limits"]["agents_md_max_bytes"]
    size = len(content.encode("utf-8"))
    if size > limit:
        raise RuntimeError(
            f"AGENTS.md is {size} bytes, over the {limit}-byte Codex "
            f"project-doc limit (DEFAULT_PROJECT_DOC_MAX_BYTES). Codex would "
            f"silently truncate it. Trim the CLAUDE.md chain."
        )
    return {REPO / "AGENTS.md": content}


