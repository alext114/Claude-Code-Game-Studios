from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CLAUDE = REPO / ".claude"
CODEX = REPO / ".codex"
MAPPINGS = Path(__file__).parent / "mappings.toml"

HEADER = (
    "<!-- GENERATED by tools/codex-sync — do not edit. Source: {source} -->"
)
HEADER_TOML = "# GENERATED by tools/codex-sync — do not edit. Source: {source}"


# --------------------------------------------------------------------------
# Loading
# --------------------------------------------------------------------------

def load_mappings() -> dict:
    with MAPPINGS.open("rb") as fh:
        return tomllib.load(fh)


def skill_names() -> list[str]:
    """The closed set of skill names. This is what makes /x -> $x safe."""
    return sorted(p.parent.name for p in CLAUDE.glob("skills/*/SKILL.md"))


def agent_names() -> list[str]:
    return sorted(p.stem for p in CLAUDE.glob("agents/*.md"))


def split_frontmatter(text: str) -> tuple[str, str]:
    """Return (frontmatter, body). Frontmatter excludes the --- delimiters."""
    if not text.startswith("---"):
        return "", text
    end = text.find("\n---", 3)
    if end == -1:
        return "", text
    return text[4:end], text[end + 4:].lstrip("\n")


# --------------------------------------------------------------------------
# Body rewriting  (port plan §6.3)
# --------------------------------------------------------------------------

def _skill_ref_pattern(names: list[str]) -> re.Pattern:
    """Match /skill-name only when it is a command reference, not a path.

    Guards against the R5 failure mode: /help must be rewritten, but
    docs/help/x and src/start/y must not.
    """
    alt = "|".join(re.escape(n) for n in sorted(names, key=len, reverse=True))
    # (?<![\w./-]) : not preceded by a path-ish character
    # (?![\w/-])   : not followed by one (so /help does not match /helper)
    return re.compile(rf"(?<![\w./-])/({alt})(?![\w/-])")


def rewrite_skill_refs(text: str, names: list[str]) -> str:
    return _skill_ref_pattern(names).sub(lambda m: "$" + m.group(1), text)


def rewrite_tool_names(text: str, mappings: dict) -> str:
    """Rewrite Claude tool names to Codex equivalents.

    Safe names are rewritten anywhere. Contextual names are English words and
    are rewritten only inside backticks or in an explicit "X tool" phrasing.
    """
    for claude, codex in mappings["tool_names"].items():
        text = re.sub(rf"\b{re.escape(claude)}\b", codex, text)

    for claude, codex in mappings["tool_names_contextual"].items():
        text = re.sub(rf"`{re.escape(claude)}`", f"`{codex}`", text)
        text = re.sub(rf"\b{re.escape(claude)} tool\b", f"{codex} tool", text)
    return text


def rewrite_body(text: str, names: list[str], mappings: dict) -> str:
    return rewrite_tool_names(rewrite_skill_refs(text, names), mappings)


# --------------------------------------------------------------------------
# Preflight assertions
# --------------------------------------------------------------------------

def assert_gated_tools() -> list[str]:
    """78 skills reference config-gated tools. Fail loudly if they are off."""
    cfg_path = CODEX / "config.toml"
    if not cfg_path.exists():
        return [f"missing {cfg_path.relative_to(REPO)}"]
    with cfg_path.open("rb") as fh:
        cfg = tomllib.load(fh)
    tools = cfg.get("tools", {})
    problems = []
    for name in load_mappings()["gated_tools"]["required"]:
        value = tools.get(name)
        enabled = value is True or (isinstance(value, dict) and value.get("enabled"))
        if not enabled:
            problems.append(f"[tools].{name} is not enabled in .codex/config.toml")
    return problems


