# --------------------------------------------------------------------------
# Preflight
# --------------------------------------------------------------------------

def assert_gated_tools(mappings: dict) -> list[str]:
    """78 skills will reference config-gated tools. Fail loudly if they are off."""
    cfg_path = CODEX / "config.toml"
    if not cfg_path.exists():
        return [f"missing {cfg_path.relative_to(REPO)}"]
    with cfg_path.open("rb") as fh:
        cfg = tomllib.load(fh)
    tools = cfg.get("tools", {})
    problems = []
    for name in mappings["gated_tools"]["required"]:
        value = tools.get(name)
        enabled = value is True or (isinstance(value, dict) and value.get("enabled"))
        if not enabled:
            problems.append(f"[tools].{name} is not enabled in .codex/config.toml")
    return problems


# --------------------------------------------------------------------------
# Emit / check
# --------------------------------------------------------------------------

def collect(mappings: dict) -> dict[Path, str]:
    outputs: dict[Path, str] = {}
    for phase in sorted(IMPLEMENTED):
        outputs.update(IMPLEMENTED[phase](mappings))
    return outputs


def emit(outputs: dict[Path, str], check: bool) -> int:
    stale = []
    for path in sorted(outputs):
        content = outputs[path]
        rel = path.relative_to(REPO)
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(rel))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"  wrote {rel} ({len(content.encode('utf-8'))} bytes)")

    if check:
        if stale:
            print("drift detected — these are stale or hand-edited:", file=sys.stderr)
            for s in stale:
                print(f"  {s}", file=sys.stderr)
            print("\nrun: python3 tools/codex-sync/sync.py", file=sys.stderr)
            return 1
        print(f"drift guard: {len(outputs)} generated file(s) current")
    return 0


# --------------------------------------------------------------------------
# Self-test  (R5 boundary cases)
# --------------------------------------------------------------------------

def self_test() -> int:
    m = load_mappings()
    names = skill_names()
    failures = 0

    def check(got, expected, note):
        nonlocal failures
        if got != expected:
            print(f"  FAIL ({note}): {got!r}, want {expected!r}")
            failures += 1

    for text, expected, note in [
        ("run /code-review on it", "run $code-review on it", "basic rewrite"),
        ("/story-readiness [path]", "$story-readiness [path]", "with arg hint"),
        ("see docs/help/index.md", "see docs/help/index.md", "path, not a ref"),
        ("src/start/main.cs", "src/start/main.cs", "path segment"),
        ("and/or", "and/or", "not a skill name"),
        ("/helper", "/helper", "prefix must not match"),
        ("`/gate-check`", "`$gate-check`", "inside backticks"),
        ("</div>", "</div>", "html closing tag"),
    ]:
        check(rewrite_skill_refs(text, names), expected, note)

    for text, expected, note in [
        ("Use AskUserQuestion here", "Use request_user_input here", "safe name"),
        ("Read the story file", "Read the story file", "English word untouched"),
        ("the `Read` tool", "the `read_file` tool", "backticked"),
        ("use the Task tool", "use the spawn_agent tool", "X tool phrasing"),
        ("a task description", "a task description", "lowercase untouched"),
    ]:
        check(rewrite_tool_names(text, m), expected, note)

    for text, expected, note in [
        ("# A\n## B", "### A\n#### B", "demote by 2"),
        ("```\n# not a heading\n```", "```\n# not a heading\n```", "fenced block"),
        ("###### deep", "###### deep", "clamps at h6"),
    ]:
        check(demote_headings(text, 2), expected, note)

    for parent, child, expected, note in [
        ("Technical Preferences", "Technical Preferences", True, "exact dup"),
        ("Coordination Rules", "Agent Coordination Rules", True, "parent in child"),
        ("Project Structure", "Directory Structure", False, "genuinely different"),
        ("Engine Version Reference", "Godot Engine — Version Reference", True,
         "parent in child, extra qualifier"),
    ]:
        check(_is_redundant(parent, child), expected, note)

    total = 8 + 5 + 3 + 4
    print(f"self-test: {total - failures}/{total} passed")
    return 1 if failures else 0


# --------------------------------------------------------------------------

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="drift guard: verify generated output is current")
    ap.add_argument("--self-test", action="store_true",
                    help="run the rewrite-rule test cases")
    ap.add_argument("--status", action="store_true",
                    help="show what is discovered and which phases are done")
    args = ap.parse_args()

    if args.self_test:
        return self_test()

    mappings = load_mappings()
    problems = assert_gated_tools(mappings)
    if problems:
        for p in problems:
            print(f"error: {p}", file=sys.stderr)
        return 1

    if args.status:
        print(f"repo            {REPO}")
        print(f"skills found    {len(skill_names())}")
        print(f"agents found    {len(agent_names())}")
        print( "gated tools     OK")
        print(f"phases done     {', '.join(str(n) for n in sorted(IMPLEMENTED))}")
        print(f"phases pending  {', '.join(str(n) for n in sorted(PENDING))}")
        return 0

    return emit(collect(mappings), check=args.check)


if __name__ == "__main__":
    sys.exit(main())
